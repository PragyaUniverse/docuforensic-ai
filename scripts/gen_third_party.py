def requirement_names(path: Path) -> list[str]:
    names = []
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        names.append(re.split(r"[\[<>=!~; ]", line, maxsplit=1)[0])
    return names


def python_license(name: str) -> tuple[str, str]:
    try:
        meta = metadata.metadata(name)
    except metadata.PackageNotFoundError:
        return "not installed", "not installed"
    version = meta.get("Version", "?")
    expression = meta.get("License-Expression")
    if expression:
        return version, expression
    classifiers = [
        c.split("::")[-1].strip() for c in meta.get_all("Classifier", [])
        if c.startswith("License ::") and "OSI Approved" != c.split("::")[-1].strip()
    ]
    if classifiers:
        return version, "; ".join(classifiers)
    raw = (meta.get("License") or "").strip()
    if raw and len(raw) < 80 and "\n" not in raw:
        return version, raw
    if raw:
        return version, raw.splitlines()[0][:70] + " (first line of license text)"
    return version, "UNKNOWN: not declared in metadata"


def node_rows() -> tuple[list[tuple[str, str, str, str]], bool]:
    manifest = REPO_ROOT / "frontend" / "package.json"
    if not manifest.exists():
        return [], False
    data = json.loads(manifest.read_text())
    rows = []
    for scope, label in (("dependencies", "runtime"), ("devDependencies", "build")):
        for name, wanted in sorted(data.get(scope, {}).items()):
            pkg = REPO_ROOT / "frontend" / "node_modules" / name / "package.json"
            if pkg.exists():
                info = json.loads(pkg.read_text())
                lic = info.get("license") or "UNKNOWN: not declared"
                if isinstance(lic, dict):
                    lic = lic.get("type", "UNKNOWN")
                rows.append((name, info.get("version", wanted), lic, label))
            else:
                rows.append((name, wanted, "not installed: run npm install", label))
    return rows, True


def main() -> int:
    lines = [STATIC_HEADER, "## Python libraries (direct dependencies)", "",
             "| Package | Version | License |", "|---|---|---|"]
    unknown = []
    for name in sorted(requirement_names(REPO_ROOT / "requirements.txt"), key=str.lower):
        version, lic = python_license(name)
        lines.append(f"| {name} | {version} | {lic} |")
        if lic.startswith("UNKNOWN") or version == "not installed":
            unknown.append(name)

    rows, present = node_rows()
    lines += ["", "## Frontend libraries (direct dependencies)", ""]
    if present:
        lines += ["| Package | Version | License | Used for |", "|---|---|---|---|"]
        lines += [f"| {n} | {v} | {lic} | {u} |" for n, v, lic, u in rows]
        unknown += [n for n, _, lic, _ in rows if lic.startswith(("UNKNOWN", "not installed"))]
    else:
        lines.append("`frontend/package.json` is not present yet.")
    lines.append(MODELS)
    OUT.write_text("\n".join(lines))
    print(f"Wrote {OUT.name}: {len(rows)} frontend packages. Unresolved: {unknown or 'none'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
