@dataclass
class CaseRun:
    """Output of detection for one case, with documents mapped back to original filenames."""

    key: str
    documents: list[Document]
    findings: list[Finding]
    filename_of: dict[str, str]  # doc_id -> original filename
    errors: list[str] = field(default_factory=list)
    seconds: float = 0.0


def _bbox(raw: Any) -> BBox | None:
    if raw is None:
        return None
    if isinstance(raw, BBox):
        return raw
    if isinstance(raw, dict):
        return BBox(**raw)
    x0, y0, x1, y1 = raw
    return BBox(x0=x0, y0=y0, x1=x1, y1=y1)


def boxes_overlap(pred: BBox | None, truth: BBox | None) -> bool:
    """True if a predicted box localizes a ground-truth box. Both must be real boxes."""
    if pred is None or truth is None or pred.area <= 0 or truth.area <= 0:
        return False
    if pred.iou(truth) >= IOU_THRESHOLD:
        return True
    ix = max(0.0, min(pred.x1, truth.x1) - max(pred.x0, truth.x0))
    iy = max(0.0, min(pred.y1, truth.y1) - max(pred.y0, truth.y0))
    inter = ix * iy
    small, large = sorted((pred.area, truth.area))
    if large / small > MAX_AREA_RATIO:
        return False
    return inter / small >= CONTAINMENT_THRESHOLD


def _candidate_boxes(finding: Finding) -> list[tuple[str | None, int | None, BBox]]:
    """(doc_id, page, bbox) for the finding's region and any located evidence."""
    out: list[tuple[str | None, int | None, BBox]] = []
    if finding.bbox is not None:
        out.append((finding.doc_id, finding.page, finding.bbox))
    for ev in finding.evidence:
        if ev.bbox is not None:
            out.append((ev.doc_id or finding.doc_id, ev.page if ev.page is not None else finding.page,
                        ev.bbox))
    return out


def finding_localizes(finding: Finding, gt: dict, filename_of: dict[str, str]) -> bool:
    truth = _bbox(gt.get("bbox"))
    for doc_id, page, box in _candidate_boxes(finding):
        if filename_of.get(doc_id or "") != gt["filename"]:
            continue
        if page != gt.get("page", 0):
            continue
        if boxes_overlap(box, truth):
            return True
    return False


def finding_doc_level_match(finding: Finding, gt: dict, filename_of: dict[str, str]) -> bool:
    """A finding with no region counts only if it names the document and an expected detector."""
    if finding.bbox is not None:
        return False
    if filename_of.get(finding.doc_id or "") != gt["filename"]:
        return False
    return finding.detector in set(gt.get("expected_detectors", []))


def _finding_filenames(finding: Finding, filename_of: dict[str, str]) -> set[str]:
    ids = [finding.doc_id, *finding.related_doc_ids]
    return {filename_of[i] for i in ids if i in filename_of}


def discrepancy_matches(finding: Finding, gt: dict, filename_of: dict[str, str]) -> bool:
    if finding.discrepancy_type != gt["discrepancy_type"]:
        return False
    wanted = set(gt.get("documents", []))
    named = _finding_filenames(finding, filename_of)
    needed = min(2, len(wanted))
    return len(named & wanted) >= needed


def _ratio(num: int, den: int) -> float | None:
    return round(num / den, 4) if den else None


def _f1(p: float | None, r: float | None) -> float | None:
    if not p or not r:
        return 0.0 if p is not None and r is not None else None
    return round(2 * p * r / (p + r), 4)


def score_detection(run: CaseRun, truth: dict) -> dict:
    manips = truth.get("manipulations", [])
    discs = truth.get("discrepancies", [])
    filename_of = run.filename_of

    manip_rows = []
    pm_matched: set[str] = set()
    explained: dict[str, str] = {}
    for gt in manips:
        strict, doc_level, any_flag, detectors = False, False, False, set()
        for f in run.findings:
            localized = finding_localizes(f, gt, filename_of)
            doc_match = finding_doc_level_match(f, gt, filename_of)
            if not (localized or doc_match):
                continue
            any_flag = True
            detectors.add(f.detector)
            if f.status == FindingStatus.POTENTIAL_MANIPULATION:
                pm_matched.add(f.id)
                strict = strict or localized
                doc_level = doc_level or doc_match
            elif f.status == FindingStatus.INCONSISTENCY:
                explained[f.id] = gt.get("id", "?")
        manip_rows.append({
            "id": gt.get("id"),
            "type": gt.get("type"),
            "filename": gt["filename"],
            "localized_potential_manipulation": strict,
            "doc_level_potential_manipulation": doc_level,
            "any_status_flagged": any_flag,
            "detectors": sorted(detectors),
        })

    # Expected within-document conflicts, such as arithmetic an injected edit breaks.
    within_rows = []
    for gt in truth.get("within_document", []):
        hits = [
            f for f in run.findings
            if f.detector == gt.get("detector")
            and f.status == FindingStatus.INCONSISTENCY
            and filename_of.get(f.doc_id) == gt.get("filename")
        ]
        for f in hits:
            explained[f.id] = gt.get("id", "?")
        within_rows.append({**gt, "found": bool(hits)})

    disc_rows = []
    disc_matched: set[str] = set()
    for gt in discs:
        hits = [f for f in run.findings if discrepancy_matches(f, gt, filename_of)]
        disc_matched.update(f.id for f in hits)
        disc_rows.append({
            "id": gt.get("id"),
            "discrepancy_type": gt["discrepancy_type"],
            "documents": gt.get("documents", []),
            "found": bool(hits),
            "finding_statuses": sorted({f.status.value for f in hits}),
        })

    clean = not manips and not discs
    unmatched: list[dict] = []
    for f in run.findings:
        is_flag = f.status in (FindingStatus.POTENTIAL_MANIPULATION, FindingStatus.INCONSISTENCY)
        matched = f.id in pm_matched or f.id in disc_matched or f.id in explained
        if clean or (is_flag and not matched):
            unmatched.append(_fp_row(run.key, f, filename_of))

    pm_total = sum(f.status == FindingStatus.POTENTIAL_MANIPULATION for f in run.findings)
    inc_total = sum(f.status == FindingStatus.INCONSISTENCY for f in run.findings)
    return {
        "case": run.key,
        "clean": clean,
        "manipulations": manip_rows,
        "discrepancies": disc_rows,
        "potential_manipulation_total": pm_total,
        "potential_manipulation_matched": len(pm_matched),
        "inconsistency_total": inc_total,
        "inconsistency_matched": sum(
            1 for f in run.findings
            if f.status == FindingStatus.INCONSISTENCY
            and (f.id in disc_matched or f.id in explained)
        ),
        "unmatched_findings": unmatched,
        "within_document": within_rows,
        "finding_counts_by_status": _count(f.status.value for f in run.findings),
        "pipeline_errors": run.errors,
        "seconds": round(run.seconds, 2),
    }


def _fp_row(case: str, f: Finding, filename_of: dict[str, str]) -> dict:
    return {
        "case": case,
        "status": f.status.value,
        "category": f.category.value,
        "detector": f.detector,
        "discrepancy_type": f.discrepancy_type,
        "severity": f.severity.value,
        "confidence": round(f.confidence, 3),
        "filename": filename_of.get(f.doc_id or "", None),
        "title": f.title,
    }


def _count(items: Iterable[str]) -> dict[str, int]:
    out: dict[str, int] = defaultdict(int)
    for i in items:
        out[i] += 1
    return dict(sorted(out.items()))


_MONEY_RE = re.compile(r"^-?\d[\d,]*(\.\d+)?$")


def normalize_value(value: Any) -> str:
    """Forgiving only about formatting: case, spacing, currency marks, separators and thousands
    commas. Every letter and digit still has to match."""
    text = re.sub(r"\s+", " ", str(value)).strip().casefold()
    text = re.sub(r"^(rs\.?|inr|₹)\s*", "", text).rstrip("/-").strip()
    if _MONEY_RE.match(text):
        try:
            return f"{float(text.replace(',', '')):.2f}"
        except ValueError:
            pass
    # Addresses and phone numbers: "Society,, Paud Rd - 411038", "+91 90000 01234".
    if re.search(r"[,+]", text):
        return re.sub(r"[\s,+\-]+", "", text)
    return text


def score_fields(run: CaseRun, truth: dict) -> list[dict]:
    """One row per ground-truth field. A field that wasn't extracted is a miss, not skipped."""
    by_name = {doc.filename: doc for doc in run.documents}
    by_original = {run.filename_of.get(doc.id): doc for doc in run.documents}
    by_name.update({k: v for k, v in by_original.items() if k})
    rows = []
    for gt_doc in truth.get("documents", []):
        doc = by_name.get(gt_doc["filename"])
        for name, spec in (gt_doc.get("fields") or {}).items():
            expected = spec["value"] if isinstance(spec, dict) else spec
            candidates = [f for f in doc.fields if f.name == name] if doc else []
            actuals = [f.value_norm or f.value_raw for f in candidates] + [
                f.value_raw for f in candidates
            ]
            value_ok = any(normalize_value(a) == normalize_value(expected) for a in actuals)
            truth_box = _bbox(spec.get("bbox")) if isinstance(spec, dict) else None
            page = spec.get("page", 0) if isinstance(spec, dict) else 0
            located = None
            if truth_box is not None:
                located = any(
                    f.page == page and _location_ok(f.bbox, truth_box) for f in candidates
                )
            rows.append({
                "case": run.key,
                "filename": gt_doc["filename"],
                "doc_type": gt_doc.get("doc_type", "unknown"),
                "format": gt_doc.get("format", "unknown"),
                "field": name,
                "expected": str(expected),
                "extracted": candidates[0].value_raw if candidates else None,
                "present": bool(candidates),
                "value_correct": value_ok,
                "location_correct": located,
            })
    return rows


def score_tables(run: CaseRun, truth: dict) -> list[dict]:
    """One row per ground-truth table row. Correct only if date and all amounts match."""
    by_name = {doc.filename: doc for doc in run.documents}
    by_name.update({k: v for k, v in ((run.filename_of.get(d.id), d) for d in run.documents) if k})
    rows = []
    for gt_doc in truth.get("documents", []):
        doc = by_name.get(gt_doc["filename"])
        for table_name, spec in (gt_doc.get("tables") or {}).items():
            if table_name != "transactions":  # pay tables have no fixed columns to compare
                continue
            extracted = [t for t in doc.tables if t.name == table_name] if doc else []
            found = [tuple(normalize_value(c.text) for c in r) for t in extracted for r in t.rows]
            for gt_row in spec.get("rows", []):
                cells = gt_row["cells"]
                key = tuple(normalize_value(c) for c in cells)
                # Every cell but free-text descriptions has to match.
                numeric = [i for i in range(len(key)) if i != 1]
                hit = any(len(f) == len(key) and all(f[i] == key[i] for i in numeric) for f in found)
                rows.append({
                    "case": run.key, "filename": gt_doc["filename"], "table": table_name,
                    "format": gt_doc.get("format", "unknown"), "row": cells, "correct": hit,
                })
    return rows


def _location_ok(pred: BBox, truth: BBox) -> bool:
    ix = max(0.0, min(pred.x1, truth.x1) - max(pred.x0, truth.x0))
    iy = max(0.0, min(pred.y1, truth.y1) - max(pred.y0, truth.y0))
    return truth.area > 0 and ix * iy / truth.area >= FIELD_BBOX_MIN_OVERLAP


def score_classification(run: CaseRun, truth: dict) -> list[dict]:
    types = {d["filename"]: d.get("doc_type") for d in truth.get("documents", [])}
    rows = []
    for doc in run.documents:
        name = run.filename_of.get(doc.id, doc.filename)
        expected = types.get(name)
        if expected is None:
            continue
        rows.append({
            "case": run.key,
            "filename": name,
            "expected": expected,
            "predicted": doc.doc_type.value,
            "correct": doc.doc_type.value == expected,
            "confidence": round(doc.doc_type_confidence, 3),
            "status": doc.status.value,
        })
    missing = set(types) - {r["filename"] for r in rows}
    rows.extend({"case": run.key, "filename": n, "expected": types[n], "predicted": None,
                 "correct": False, "confidence": 0.0, "status": "not_run"} for n in sorted(missing))
    return rows


def aggregate(per_case: list[dict], field_rows: list[dict], class_rows: list[dict],
              table_rows: list[dict] | None = None) -> dict:
    table_rows = table_rows or []
    manips = [m for c in per_case for m in c["manipulations"]]
    discs = [d for c in per_case for d in c["discrepancies"]]
    pm_total = sum(c["potential_manipulation_total"] for c in per_case)
    pm_matched = sum(c["potential_manipulation_matched"] for c in per_case)
    inc_total = sum(c["inconsistency_total"] for c in per_case)
    inc_matched = sum(c["inconsistency_matched"] for c in per_case)
    within = [w for c in per_case for w in c.get("within_document", [])]

    localized = sum(m["localized_potential_manipulation"] for m in manips)
    with_doc = sum(
        m["localized_potential_manipulation"] or m["doc_level_potential_manipulation"]
        for m in manips
    )
    any_flag = sum(m["any_status_flagged"] for m in manips)
    precision = _ratio(pm_matched, pm_total)
    recall = _ratio(localized, len(manips))

    by_type: dict[str, dict[str, int]] = defaultdict(lambda: {"found": 0, "total": 0})
    for d in discs:
        by_type[d["discrepancy_type"]]["total"] += 1
        by_type[d["discrepancy_type"]]["found"] += int(d["found"])

    manip_by_type: dict[str, dict[str, int]] = defaultdict(
        lambda: {"localized": 0, "any_flag": 0, "total": 0}
    )
    for m in manips:
        row = manip_by_type[m.get("type") or "unknown"]
        row["total"] += 1
        row["localized"] += int(m["localized_potential_manipulation"])
        row["any_flag"] += int(m["any_status_flagged"])

    clean_cases = [c for c in per_case if c["clean"]]
    return {
        "cases": len(per_case),
        "manipulation": {
            "ground_truth_total": len(manips),
            "predictions_potential_manipulation": pm_total,
            "predictions_matched": pm_matched,
            "precision": precision,
            "recall_localized": recall,
            "f1_localized": _f1(precision, recall),
            "recall_including_doc_level": _ratio(with_doc, len(manips)),
            "recall_any_status": _ratio(any_flag, len(manips)),
            "by_type": {k: dict(v) for k, v in sorted(manip_by_type.items())},
        },
        "discrepancy": {
            "ground_truth_total": len(discs),
            "found": sum(d["found"] for d in discs),
            "recall": _ratio(sum(d["found"] for d in discs), len(discs)),
            "distinct_types_found": sorted(t for t, v in by_type.items() if v["found"]),
            "distinct_types_total": sorted(by_type),
            "by_type": {
                t: {**v, "recall": _ratio(v["found"], v["total"])}
                for t, v in sorted(by_type.items())
            },
        },
        "inconsistency": {
            "total": inc_total,
            "matched": inc_matched,
            "precision": _ratio(inc_matched, inc_total),
        },
        "within_document": {
            "total": len(within),
            "found": sum(w["found"] for w in within),
            "recall": _ratio(sum(w["found"] for w in within), len(within)),
        },
        "fields": _field_summary(field_rows),
        "tables": {
            "total": len(table_rows),
            "correct": sum(r["correct"] for r in table_rows),
            "accuracy": _ratio(sum(r["correct"] for r in table_rows), len(table_rows)),
            "by_format": _group_accuracy(table_rows, "format", "correct"),
        },
        "classification": {
            "total": len(class_rows),
            "correct": sum(r["correct"] for r in class_rows),
            "accuracy": _ratio(sum(r["correct"] for r in class_rows), len(class_rows)),
            "by_expected": _group_accuracy(class_rows, "expected", "correct"),
        },
        "clean_cases": {
            "cases": [c["case"] for c in clean_cases],
            "potential_manipulation_findings": sum(
                c["potential_manipulation_total"] for c in clean_cases
            ),
            "inconsistency_findings": sum(c["inconsistency_total"] for c in clean_cases),
            "all_findings": sum(sum(c["finding_counts_by_status"].values()) for c in clean_cases),
        },
        "pipeline_errors": sum(len(c["pipeline_errors"]) for c in per_case),
        "seconds": round(sum(c["seconds"] for c in per_case), 2),
    }


def _group_accuracy(rows: list[dict], key: str, metric: str) -> dict[str, dict]:
    groups: dict[str, list[dict]] = defaultdict(list)
    for r in rows:
        groups[str(r[key])].append(r)
    return {
        k: {"total": len(v), "correct": sum(bool(x[metric]) for x in v),
            "accuracy": _ratio(sum(bool(x[metric]) for x in v), len(v))}
        for k, v in sorted(groups.items())
    }


def _field_summary(rows: list[dict]) -> dict:
    located = [r for r in rows if r["location_correct"] is not None]
    return {
        "total": len(rows),
        "present": sum(r["present"] for r in rows),
        "value_correct": sum(r["value_correct"] for r in rows),
        "value_accuracy": _ratio(sum(r["value_correct"] for r in rows), len(rows)),
        "location_checked": len(located),
        "location_correct": sum(bool(r["location_correct"]) for r in located),
        "location_accuracy": _ratio(sum(bool(r["location_correct"]) for r in located), len(located)),
        "by_doc_type": _group_accuracy(rows, "doc_type", "value_correct"),
        "by_format": _group_accuracy(rows, "format", "value_correct"),
    }


