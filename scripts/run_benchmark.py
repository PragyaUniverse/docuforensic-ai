def anonymize(filename: str) -> str:
    """Opaque stable name, so a classifier can't read the answer from the filename."""
    digest = hashlib.sha256(filename.encode()).hexdigest()[:10]
    return f"doc_{digest}{Path(filename).suffix.lower()}"


def stage_copy(files: list[Path], dest: Path) -> dict[str, Path]:
    """Copy only document files. ground_truth.json is structurally unreachable from here."""
    dest.mkdir(parents=True, exist_ok=True)
    out = {}
    for f in files:
        if f.suffix.lower() not in DOC_SUFFIXES:
            raise ValueError(f"refusing to pass a non-document file to detection: {f.name}")
        target = dest / anonymize(f.name)
        shutil.copy2(f, target)
        out[f.name] = target
    return out


def run_pipeline(key: str, files: list[Path], workroot: Path) -> CaseRun:
    """Module order from docs/CONTRACTS.md section 2, without the LLM (it can't change statuses)."""
    errors: list[str] = []

    def guarded(stage: str, fn, *args, default=None):
        try:
            return fn(*args)
        except Exception as exc:  # noqa: BLE001 - recorded in the report
            detail = traceback.format_exception_only(type(exc), exc)[-1].strip()
            errors.append(f"{stage}: {detail}")
            return default

    from backend.contextual import verify_within_document
    from backend.crossdoc import build_entities, correlate
    from backend.orchestrator import apply_visible_readings
    from pipeline.classify import classify
    from pipeline.extract import extract_fields
    from pipeline.forensics_pdf import analyze_pdf
    from pipeline.forensics_visual import analyze_visual
    from pipeline.fusion import fuse_regions
    from pipeline.signatures import analyze_signatures
    from pipeline.structure import analyze_structure

    from pipeline.ingest import ingest_file
    from pipeline.ocr import extract_words

    start = time.perf_counter()
    case_id = new_id("bench")
    workdir = workroot / case_id
    workdir.mkdir(parents=True, exist_ok=True)
    copies = stage_copy(files, workroot / f"{case_id}_input")

    docs: list[Document] = []
    sources: dict[str, Path] = {}
    filename_of: dict[str, str] = {}
    for original, path in copies.items():
        doc = guarded(f"ingest[{original}]", ingest_file, path, case_id, workdir, path.name)
        if doc is None:
            continue
        filename_of[doc.id] = original
        sources[doc.id] = path
        docs.append(doc)

    findings: list[Finding] = []
    for i, doc in enumerate(docs):
        name = filename_of[doc.id]
        for stage, fn, args in (
            ("ocr", extract_words, (doc, workdir)),
            ("classify", classify, (doc,)),
            ("extract", extract_fields, (doc,)),
            ("structure", analyze_structure, (doc,)),
        ):
            updated = guarded(f"{stage}[{name}]", fn, *args)
            if updated is not None:
                doc = updated
        docs[i] = doc
        findings += guarded(f"visual[{name}]", analyze_visual, doc, workdir, default=[])
        findings += guarded(f"pdf[{name}]", analyze_pdf, doc, sources[doc.id], workdir, default=[])

    findings += guarded("signatures", analyze_signatures, docs, workdir, case_id, default=[])

    fused: list[Finding] = [f for f in findings if f.doc_id not in {d.id for d in docs}]
    for doc in docs:
        own = [f for f in findings if f.doc_id == doc.id]
        fused += guarded(f"fusion[{filename_of[doc.id]}]", fuse_regions, own, doc, default=own)
    # Same step, same place as backend/orchestrator.py, so this measures the system that actually runs.
    guarded("visible_readings", apply_visible_readings, docs, fused)
    for doc in docs:
        fused += guarded(
            f"contextual[{filename_of[doc.id]}]", verify_within_document, doc, default=[]
        )

    entities = guarded("entities", build_entities, docs, case_id, default=[])
    fused += guarded("correlate", correlate, docs, entities, case_id, default=[])
    return CaseRun(key, docs, fused, filename_of, errors, time.perf_counter() - start)


@dataclass
class BenchCase:
    key: str
    files: list[Path]
    truth_path: Path
    noise: str | None = None


def load_truth(case: BenchCase) -> dict:
    """Read only after detection. For noise groups, restrict truth to the group's files."""
    truth = json.loads(case.truth_path.read_text())
    if case.noise is None:
        return truth
    names = {f.name for f in case.files}
    truth["documents"] = [d for d in truth.get("documents", []) if d["filename"] in names]
    truth["manipulations"] = [m for m in truth.get("manipulations", []) if m["filename"] in names]
    truth["discrepancies"] = [
        d for d in truth.get("discrepancies", [])
        if len(set(d.get("documents", [])) & names) >= 2
    ]
    return truth


def discover_cases(root: Path, include_noise: bool, only: list[str] | None) -> list[BenchCase]:
    cases: list[BenchCase] = []
    for truth in sorted(root.glob("*/ground_truth.json")):
        folder = truth.parent
        if folder.name in {"noise_variants", "unsupported"}:
            continue
        if only and folder.name not in only:
            continue
        files = sorted(p for p in folder.iterdir() if p.suffix.lower() in DOC_SUFFIXES)
        cases.append(BenchCase(folder.name, files, truth))
    if not include_noise:
        return cases
    for truth in sorted((root / "noise_variants").glob("*/ground_truth.json")):
        folder = truth.parent
        if only and folder.name not in only:
            continue
        groups: dict[str, list[Path]] = defaultdict(list)
        for p in sorted(folder.iterdir()):
            match = NOISE_RE.search(p.name)
            if match and p.suffix.lower() in DOC_SUFFIXES:
                groups[match.group(1)].append(p)
        # Reuse can only be seen with the document it was reused from, so that original (not itself
        # degraded) joins the group. Without it these would be scored as misses no system could avoid.
        sources: list[Path] = []
        parent_truth = root / folder.name / "ground_truth.json"
        if parent_truth.exists():
            for m in json.loads(parent_truth.read_text()).get("manipulations", []):
                source = m.get("source_filename")
                if source and (root / folder.name / source).exists():
                    sources.append(root / folder.name / source)
        for kind, files in sorted(groups.items()):
            cases.append(BenchCase(f"{folder.name}__{kind}", [*files, *sources], truth, kind))
    return cases


def git_state() -> dict:
    def run(*args: str) -> str:
        return subprocess.run(
            ["git", *args], cwd=REPO_ROOT, capture_output=True, text=True, check=False
        ).stdout.strip()

    return {"commit": run("rev-parse", "HEAD") or "unknown", "dirty": bool(run("status", "--porcelain"))}


def _pct(v: float | None) -> str:
    return "n/a" if v is None else f"{v * 100:.1f}%"


def render_markdown(result: dict) -> str:
    g = result["git"]
    s = result["summary_clean_scans"]
    n = result.get("summary_noise")
    lines = [
        "# Benchmark Results",
        "",
        (
            f"Generated {result['generated_at']} at commit `{g['commit'][:10]}`"
            + (" (with uncommitted changes)." if g["dirty"] else ".")
        ),
        "",
        f"> {DISCLOSURE}",
        "",
        (
            f"Detection ran on anonymized copies of the documents, without the LLM. Boxes match on "
            f"IoU ≥ {IOU_THRESHOLD} or containment ≥ {CONTAINMENT_THRESHOLD} with an area ratio up "
            f"to {MAX_AREA_RATIO:g}."
        ),
        "",
        "## Original documents",
        "",
        *_summary_table(s),
    ]
    if n:
        lines += ["", "## Noise variants (rotation, blur, JPEG)", "", *_summary_table(n)]
    per_case_header = (
        "| Case | Potential manipulation | Inconsistency | Unmatched flags | Pipeline errors "
        "| Seconds |"
    )
    lines += ["", "## Per case", "", per_case_header, "|---|---|---|---|---|---|"]
    for c in result["cases"]:
        lines.append(
            f"| {c['case']} | {c['potential_manipulation_matched']}/"
            f"{c['potential_manipulation_total']} matched | {c['inconsistency_matched']}/"
            f"{c['inconsistency_total']} matched | {len(c['unmatched_findings'])} | "
            f"{len(c['pipeline_errors'])} | {c['seconds']} |"
        )
    missed = [
        (c["case"], m) for c in result["cases"] for m in c["manipulations"]
        if not m["localized_potential_manipulation"]
    ]
    lines += ["", "## Manipulations not localized as potential manipulation", ""]
    lines += [
        f"- `{case}`: {m['id']} {m['type']} in `{m['filename']}` "
        f"(flagged at any status: {'yes' if m['any_status_flagged'] else 'no'})"
        for case, m in missed
    ] or ["None."]
    missed_disc = [
        (c["case"], d) for c in result["cases"] for d in c["discrepancies"] if not d["found"]
    ]
    lines += ["", "## Discrepancies missed", ""]
    lines += [
        f"- `{case}`: {d['id']} {d['discrepancy_type']}" for case, d in missed_disc
    ] or ["None."]
    fps = [f for c in result["cases"] for f in c["unmatched_findings"]]
    inventory_note = (
        "Every potential manipulation or inconsistency with no ground-truth match, plus every "
        "finding on a clean case. Treat these as false positives unless reviewed."
    )
    lines += ["", f"## Unmatched findings ({len(fps)})", "", inventory_note, ""]
    if fps:
        lines += ["| Case | Status | Detector | File | Confidence | Title |",
                  "|---|---|---|---|---|---|"]
        lines += [
            f"| {f['case']} | {f['status']} | {f['detector']} | {f['filename'] or '-'} | "
            f"{f['confidence']} | {str(f['title']).replace('|', '/')} |"
            for f in fps
        ]
    else:
        lines.append("None.")
    errs = [(c["case"], e) for c in result["cases"] for e in c["pipeline_errors"]]
    lines += ["", "## Pipeline errors", ""]
    lines += [f"- `{case}`: {e}" for case, e in errs] or ["None."]
    return "\n".join(lines) + "\n"


def _summary_table(s: dict) -> list[str]:
    m, d, f, c, cl = (s["manipulation"], s["discrepancy"], s["fields"], s["classification"],
                      s["clean_cases"])
    rows = [
        ("Manipulation precision", _pct(m["precision"]),
         f"{m['predictions_matched']}/{m['predictions_potential_manipulation']} predictions"),
        ("Manipulation recall (localized)", _pct(m["recall_localized"]),
         f"of {m['ground_truth_total']} injected"),
        ("Manipulation recall (incl. document-level)", _pct(m["recall_including_doc_level"]),
         "region-less findings from an expected detector"),
        ("Manipulation flagged at any status", _pct(m["recall_any_status"]), ""),
        ("Discrepancy recall", _pct(d["recall"]),
         (f"{d['found']}/{d['ground_truth_total']}; "
          f"{len(d['distinct_types_found'])}/{len(d['distinct_types_total'])} types")),
        ("Within-document conflict recall", _pct(s["within_document"]["recall"]),
         f"{s['within_document']['found']}/{s['within_document']['total']}"),
        ("Field value accuracy", _pct(f["value_accuracy"]), f"{f['value_correct']}/{f['total']}"),
        ("Field location accuracy", _pct(f["location_accuracy"]),
         f"{f['location_correct']}/{f['location_checked']}"),
        ("Table row accuracy", _pct(s["tables"]["accuracy"]),
         f"{s['tables']['correct']}/{s['tables']['total']} rows"),
        ("Classification accuracy", _pct(c["accuracy"]), f"{c['correct']}/{c['total']}"),
        ("Flags on clean cases", str(cl["potential_manipulation_findings"]
                                     + cl["inconsistency_findings"]),
         f"{cl['all_findings']} findings of any status"),
        ("Pipeline errors", str(s["pipeline_errors"]), ""),
    ]
    out = ["| Metric | Result | Basis |", "|---|---|---|"]
    out += [f"| {a} | {b} | {c_} |" for a, b, c_ in rows]
    out += ["", "| Discrepancy type | Found | Total |", "|---|---|---|"]
    out += [f"| {t} | {v['found']} | {v['total']} |" for t, v in d["by_type"].items()]
    out += ["", "| Field accuracy by doc type | Correct | Total | Accuracy |", "|---|---|---|---|"]
    out += [f"| {t} | {v['correct']} | {v['total']} | {_pct(v['accuracy'])} |"
            for t, v in f["by_doc_type"].items()]
    out += ["", "| Field accuracy by format | Correct | Total | Accuracy |", "|---|---|---|---|"]
    out += [f"| {t} | {v['correct']} | {v['total']} | {_pct(v['accuracy'])} |"
            for t, v in f["by_format"].items()]
    return out


def benchmark(cases: list[BenchCase]) -> dict:
    table_rows: dict[str, list[dict]] = {"orig": [], "noise": []}
    per_case, field_rows, class_rows = {"orig": [], "noise": []}, {"orig": [], "noise": []}, {
        "orig": [], "noise": []}
    with tempfile.TemporaryDirectory(prefix="docuforensic-bench-") as tmp:
        for case in cases:
            print(f"[benchmark] {case.key}: {len(case.files)} document(s)", flush=True)
            run = run_pipeline(case.key, case.files, Path(tmp))
            truth = load_truth(case)  # only now: detection has finished
            bucket = "noise" if case.noise else "orig"
            per_case[bucket].append(score_detection(run, truth))
            field_rows[bucket] += score_fields(run, truth)
            table_rows[bucket] += score_tables(run, truth)
            class_rows[bucket] += score_classification(run, truth)
    result = {
        "generated_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "git": git_state(),
        "disclosure": DISCLOSURE,
        "matching": {"iou": IOU_THRESHOLD, "containment": CONTAINMENT_THRESHOLD,
                     "max_area_ratio": MAX_AREA_RATIO},
        "summary_clean_scans": aggregate(per_case["orig"], field_rows["orig"], class_rows["orig"], table_rows["orig"]),
        "cases": per_case["orig"] + per_case["noise"],
        "field_rows": field_rows["orig"] + field_rows["noise"],
        "classification_rows": class_rows["orig"] + class_rows["noise"],
    }
    if per_case["noise"]:
        result["summary_noise"] = aggregate(
            per_case["noise"], field_rows["noise"], class_rows["noise"], table_rows["noise"]
        )
    return result


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--dataset", type=Path, default=REPO_ROOT / "data" / "synthetic_cases")
    parser.add_argument("--cases", nargs="*", help="Only these case folders")
    parser.add_argument("--no-noise", action="store_true", help="Skip noise variants")
    parser.add_argument("--out", type=Path, default=REPO_ROOT / "docs")
    args = parser.parse_args(argv)

    cases = discover_cases(args.dataset, not args.no_noise, args.cases)
    if not cases:
        print(f"No cases with ground_truth.json under {args.dataset}. Nothing written.",
              file=sys.stderr)
        return 2
    try:
        result = benchmark(cases)
    except ImportError as exc:
        print(f"Pipeline modules are not available yet ({exc}). Nothing written.", file=sys.stderr)
        return 2
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "benchmark_results.json").write_text(json.dumps(result, indent=2, default=str))
    (args.out / "benchmark_results.md").write_text(render_markdown(result))
    s = result["summary_clean_scans"]
    print(json.dumps({
        "precision": s["manipulation"]["precision"],
        "recall_localized": s["manipulation"]["recall_localized"],
        "discrepancy_recall": s["discrepancy"]["recall"],
        "within_document_recall": s["within_document"]["recall"],
        "inconsistency_precision": s["inconsistency"]["precision"],
        "field_accuracy": s["fields"]["value_accuracy"],
        "table_row_accuracy": s["tables"]["accuracy"],
        "classification": s["classification"]["accuracy"],
        "clean_case_flags": s["clean_cases"]["potential_manipulation_findings"]
        + s["clean_cases"]["inconsistency_findings"],
        "pipeline_errors": s["pipeline_errors"],
    }, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
