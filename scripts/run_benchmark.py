# Overlap rules. A prediction may match on IoU, or on containment provided the two boxes are of
# comparable size. MAX_AREA_RATIO is what stops a whole-page box from matching everything.
IOU_THRESHOLD = 0.10
CONTAINMENT_THRESHOLD = 0.50
MAX_AREA_RATIO = 12.0
FIELD_BBOX_MIN_OVERLAP = 0.30

DISCLOSURE = (
    "These numbers come from a small **synthetic** demo set generated by this project. Detector "
    "thresholds were tuned on this same data, so they are **not generalization estimates** and say "
    "little about performance on real documents. There is no held-out test set."
)


