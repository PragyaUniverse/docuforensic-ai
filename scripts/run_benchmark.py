"""Benchmark the real pipeline against the synthetic demo set.

Honesty properties this script enforces:

* Detection never sees ground truth. Only document files are copied to a temp folder, under
  anonymized names (doc_<hash>.<ext>), so neither ground_truth.json nor a telling filename can
  reach a detector or the classifier. Ground truth is read only after detection finished.
* A page-sized box can't claim credit: overlap matching rejects boxes far larger than the target.
* Zero denominators are reported as n/a, never as 100%.
* Pipeline errors are reported in the output. A broken stage lowers recall visibly.
* Every POTENTIAL_MANIPULATION or INCONSISTENCY with no ground-truth match is listed by name, and
  so is every finding on a clean case.

Usage:
    .venv/bin/python -m scripts.run_benchmark [--cases KEY ...] [--no-noise] [--out docs]
"""
